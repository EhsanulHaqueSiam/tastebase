/** Resource categories, in the order the site and agents list them. */
export const resourceKinds = {
  references: "References",
  inspiration: "Inspiration",
  parts: "Part galleries",
  fonts: "Fonts",
  colour: "Colour",
  icons: "Icons",
  illustrations: "Illustrations",
  mockups: "Mockups",
  assets: "Assets",
  "agent-tools": "Agent tools",
  tools: "Tools",
  directories: "Component directories",
  reviewed: "Reviewed, not picked",
} as const;
export type ResourceKind = keyof typeof resourceKinds;
export const isResourceKind = (id: string): id is ResourceKind => Object.hasOwn(resourceKinds, id);
/** Categories agents are pointed at. The rest are on the site and answer `get <category>`, never advertised: "reviewed"
 *  lists what tastebase looked at and does not recommend; galleries to browse, mockups, icon finders (agents install
 *  an icon library) and tools (editors, hosts, recorders) do not help an agent build a UI. A `get` answer shows a
 *  category's first ten, so put the best first. */
const siteOnly: ResourceKind[] = ["inspiration", "icons", "mockups", "tools", "reviewed"];
export const agentResourceKinds = (Object.keys(resourceKinds) as ResourceKind[]).filter((k) => !siteOnly.includes(k));

